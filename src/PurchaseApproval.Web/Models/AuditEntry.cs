// Append-only audit record for staff-account, employee-access and approval-decision events.
// Execution outcomes keep their own TransferAuditEntry table; this table covers every other
// accountable change so that "who did what, to whom, when" survives later profile edits.
// Secrets (passwords, access keys, temporary credentials) are never written here.
namespace PurchaseApproval.Models;

/// <summary>Groups audit rows by the kind of record they describe.</summary>
public enum AuditCategory
{
    StaffAccount = 1,
    EmployeeAccess = 2,
    ApprovalDecision = 3
}

/// <summary>
/// Stable integer codes for every audited action. The numeric gaps leave room for new actions
/// inside each category without renumbering, and the database check constraint lists them all.
/// </summary>
public enum AuditAction
{
    StaffAccountCreated = 1,
    StaffAccountDeactivated = 2,
    StaffAccountReactivated = 3,
    StaffRoleChanged = 4,
    StaffPasswordResetInitiated = 5,
    StaffPasswordChanged = 6,
    StaffPasswordSetupCompleted = 7,

    EmployeeCreated = 20,
    EmployeeProfileUpdated = 21,
    EmployeeDisabled = 22,
    EmployeeEnabled = 23,
    EmployeeRevoked = 24,
    EmployeeAccessRestored = 25,
    EmployeeKeyReplaced = 26,
    EmployeeDeleted = 27,

    RequestApproved = 40,
    RequestRejected = 41,
    RequestSelfApproved = 42
}

public class AuditEntry
{
    public int Id { get; set; }

    public AuditCategory Category { get; set; }

    public AuditAction Action { get; set; }

    // The record acted upon, stored as a name plus ID so the row stays meaningful even if the
    // subject is later renamed or deactivated. Example: "Employee" / 12 / "a.rahimi".
    public string SubjectType { get; set; } = string.Empty;

    public int SubjectId { get; set; }

    public string SubjectLabel { get; set; } = string.Empty;

    // Null only for actions performed by the system itself; human actions keep the account ID.
    public int? ActorUserId { get; set; }

    public ApplicationUser? ActorUser { get; set; }

    public string ActorFullNameSnapshot { get; set; } = string.Empty;

    public string ActorRoleSnapshot { get; set; } = string.Empty;

    // Free-text summary of what changed (old/new state, reason). Must never contain a secret.
    public string? Details { get; set; }

    // Always generated by the server.
    public DateTimeOffset RecordedAtUtc { get; set; } = DateTimeOffset.UtcNow;
}
