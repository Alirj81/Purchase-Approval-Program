namespace PurchaseApproval.Models;

public class TransferAuditEntry
{
    public int Id { get; set; }

    public int TransferOutcomeId { get; set; }

    public TransferOutcome TransferOutcome { get; set; }
        = null!;

    public TransferAuditAction Action { get; set; }

    // Snapshot of the transfer state after this action
    public TransferStatus StatusAfterAction { get; set; }

    public bool IsClosedAfterAction { get; set; }
    public TransferMethod? Method { get; set; }
    public string? OtherMethodDescription { get; set; }

    public string? DestinationAccountOrCardNumber { get; set; }

    public string? BankName { get; set; }

    public string? ChequeNumber { get; set; }

    public DateOnly? ChequeDate { get; set; }

public string? ChequePayeeName { get; set; }

    // The authenticated user who performed this action
    public int ActorUserId { get; set; }

    public ApplicationUser ActorUser { get; set; }
        = null!;

    public string ActorFullNameSnapshot { get; set; }
        = string.Empty;

    public string ActorRoleSnapshot { get; set; }
        = string.Empty;

    // Snapshot of the reported transaction information
    public DateTimeOffset? TransactionOccurredAtUtc { get; set; }

    public short? TransactionUtcOffsetMinutes { get; set; }

    public string? FailureReason { get; set; }

    public string? ExternalReference { get; set; }

    public string? Notes { get; set; }

    // Always generated by the server
    public DateTimeOffset RecordedAtUtc { get; set; }
        = DateTimeOffset.UtcNow;
}