// The single, final management decision for a payment request. Exactly one row may exist per
// request (unique index) and it is never edited; a new decision would require a separately
// specified reversal workflow. Rules live in ApprovalDecisionRules.
namespace PurchaseApproval.Models;

public class ApprovalDecision
{
    public int Id { get; set; }

    public int PaymentRequestId { get; set; }

    public PaymentRequest PaymentRequest { get; set; }
        = null!;

    public ApprovalDecisionType DecisionType { get; set; }

    public int DecidedByUserId { get; set; }

    public ApplicationUser DecidedByUser { get; set; }
        = null!;

    // Preserves the administrator's name at decision time
    public string DecidedByFullNameSnapshot { get; set; }
        = string.Empty;

    // Intended for the requester; shown in their authenticated history, never on the
    // bearer-token tracking page. It is not an internal-notes field.
    public string? RejectionReason { get; set; }

    // Set server-side when the deciding administrator is also the request's administrator
    // requester. Historical rows were back-filled from the preserved identities by migration.
    public bool IsSelfApproval { get; set; }

    // Generated by the server, not entered by the administrator
    public DateTimeOffset DecidedAtUtc { get; set; }
        = DateTimeOffset.UtcNow;
}
